let current = "en";

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "en";
  document.documentElement.lang = current;
}

export function lang() {
  return current;
}

/** Text by key with {placeholders}; falls back to English, then to the key itself. */
export function t(key, vars = {}) {
  const s = T[current][key] ?? T.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function allergenName(id) {
  return ALLERGEN_NAMES[current][id] ?? id;
}

export function formatDate(iso, opts = { day: "numeric", month: "long", year: "numeric" }) {
  const locale = current === "ru" ? "ru-RU" : current === "de" ? "de-DE" : "en-GB";
  return new Date(iso).toLocaleDateString(locale, opts);
}
