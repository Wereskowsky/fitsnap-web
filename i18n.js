/** Same mapping as langOf() in the backend: Belarusian and Kazakh users get Russian. */
export function langOf(code) {
  const c = (code || "").toLowerCase();
  if (c.startsWith("ru") || c.startsWith("be") || c.startsWith("kk")) return "ru";
  if (c.startsWith("de")) return "de";
  return "en";
}

